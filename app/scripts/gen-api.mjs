// Makes src/engine/openapi.json and src/engine/schema.d.ts from the engine's own API table
// (meshdoctor/api_v1.py) and result schemas (meshdoctor/schemas/), so the app can't drift from it.
//
//   npm run gen:api       write both files
//   npm run check:api     fail if they differ from what the engine says now (CI runs this)
//
// Needs Python 3 (python3, or python on Windows; PYTHON=... to choose).
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(app, "..");
const outDir = path.join(app, "src", "engine");
const check = process.argv.includes("--check");

const python = process.env.PYTHON || (process.platform === "win32" ? "python" : "python3");
const code = "import sys, json; sys.path.insert(0, 'meshdoctor'); import api_v1; "
  + "print(json.dumps(api_v1.openapi(), sort_keys=True))";
const raw = execFileSync(python, ["-c", code], {
  cwd: repo, encoding: "utf8",
  env: { ...process.env, MESHDOCTOR_CONFIG: process.platform === "win32" ? "NUL" : "/dev/null" },
});
const doc = JSON.parse(raw);

// The result documents are separate JSON Schemas (served under /api/v1/schemas/{kind}).
// Put each one into components/schemas, its $defs alongside, and point the refs at them.
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
function walk(node, fn) {
  if (Array.isArray(node)) node.forEach((n) => walk(n, fn));
  else if (node && typeof node === "object") {
    fn(node);
    Object.values(node).forEach((n) => walk(n, fn));
  }
}
const schemaDir = path.join(repo, "meshdoctor", "schemas");
for (const file of fs.readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const kind = file.replace(".schema.json", "");
  const s = JSON.parse(fs.readFileSync(path.join(schemaDir, file), "utf8"));
  walk(s, (n) => {
    if (typeof n.$ref === "string" && n.$ref.startsWith("#/$defs/")) {
      n.$ref = `#/components/schemas/${cap(kind)}_${n.$ref.slice(8)}`;
    }
  });
  for (const [name, def] of Object.entries(s.$defs || {})) doc.components.schemas[`${cap(kind)}_${name}`] = def;
  delete s.$defs; delete s.$schema; delete s.$id;
  doc.components.schemas[cap(kind)] = s;
}
walk(doc, (n) => {
  if (typeof n.$ref === "string" && n.$ref.startsWith("schemas/")) n.$ref = `#/components/schemas/${cap(n.$ref.slice(8))}`;
});

const json = JSON.stringify(doc, null, 2) + "\n";
const header = "// Generated by scripts/gen-api.mjs from the engine's API table: do not edit.\n"
  + "// Run `npm run gen:api` after changing meshdoctor/api_v1.py or meshdoctor/schemas/.\n";
const ts = header + astToString(await openapiTS(doc, { alphabetize: true, emptyObjectsUnknown: true })).replace(/\r\n/g, "\n");

const files = { "openapi.json": json, "schema.d.ts": ts };
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const p = path.join(outDir, name);
  if (check) {
    const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n") : "";
    if (cur !== text) { console.error(`stale: src/engine/${name} (run npm run gen:api)`); stale++; }
  } else {
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(p, text);
    console.log(`wrote src/engine/${name} (${text.length.toLocaleString()} bytes)`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("API types match the engine");
}
